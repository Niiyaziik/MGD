                    document.addEventListener("DOMContentLoaded", async () => {
                        const params = new URLSearchParams(window.location.search);
                        const district = Number(params.get("district"));

                        const titleEl = document.getElementById("district-title");
                        const boundsEl = document.getElementById("district-bounds");

                        // 1) Проверка корректности ID
                        if (!district) {
                            titleEl.textContent = "Округ не найден";
                            boundsEl.textContent = "Некорректный параметр id.";
                            return;
                        }

                        // 2) Подставляем ID в заголовок
                        titleEl.textContent = `Границы округа ${district}`;

                        try {
                            // 3) Запрос данных
                            const res = await fetch(`/district?format=json&district=${district}`, {
                                headers: { "Accept": "application/json" }
                            });

                            if (!res.ok) throw new Error("Ошибка загрузки");

                            const data = await res.json();
                            console.log(data);

                            if (Array.isArray(data)) {

                                //  Группируем: street → [houses]
                                const grouped = {};

                                data.forEach(row => {
                                    const street = row.street || '';
                                    const house = row.house || '';

                                    if (!grouped[street]) {
                                        grouped[street] = [];
                                    }
                                    if (house) {
                                        grouped[street].push(house);
                                    }
                                });

                                // Формируем строки по одной улице
                                const lines = Object.entries(grouped).map(([street, houses]) => {
                                    if (houses.length > 0) {
                                        return `ул.${street}: ${houses.join(', ')}`;
                                    } else {
                                        return `ул.${street}: (нет домов)`;
                                    }
                                });

                                boundsEl.textContent = lines.join('\n');
                            }
                        } catch (err) {
                            console.error(err);
                            boundsEl.textContent = "Ошибка загрузки данных.";
                        }
                    });

                </script>
